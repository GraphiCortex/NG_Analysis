def annotate_edges(
    edges,
    mapping,
):

    if edges.empty:
        return edges.copy()

    id_to_gene = (
        mapping
        .drop_duplicates(
            "stringId"
        )
        .set_index(
            "stringId"
        )[
            "queryItem"
        ]
        .to_dict()
    )

    output = edges.copy()

    output.insert(
        0,
        "Gene_A",
        output[
            "stringId_A"
        ].map(
            id_to_gene
        ),
    )

    output.insert(
        1,
        "Gene_B",
        output[
            "stringId_B"
        ].map(
            id_to_gene
        ),
    )

    return output


def make_node_table(
    master,
    mapping,
    metrics,
):

    map_cols = [
        col
        for col in [
            "queryItem",
            "stringId",
            "preferredName",
            "annotation",
        ]
        if col in mapping.columns
    ]

    map_small = (
        mapping[
            map_cols
        ]
        .rename(
            columns={
                "queryItem":
                    "Gene"
            }
        )
    )

    nodes = master.copy()

    nodes = nodes.merge(
        map_small,
        on="Gene",
        how="left",
    )

    if not metrics.empty:

        metric_cols = [
            col
            for col
            in metrics.columns
            if col not in [
                "graph_gene",
                "preferredName",
            ]
        ]

        nodes = nodes.merge(
            metrics[
                metric_cols
            ],
            on="stringId",
            how="left",
        )

    nodes[
        "mapping_status"
    ] = nodes[
        "stringId"
    ].notna().map(
        {
            True: "mapped",
            False: "unmapped",
        }
    )

    return nodes


