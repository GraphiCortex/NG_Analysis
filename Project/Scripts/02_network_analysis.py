def run_enrichment(
    session,
    genes,
    label,
    raw_dir,
    processed_dir,
    *,
    alpha=0.05,
    correction="fdr",
    exclude_iea=False,
    background=None,
    refresh=False,
):

    h = gene_hash(genes)

    iea_tag = (
        "noIEA"
        if exclude_iea
        else "withIEA"
    )

    alpha_tag = (
        str(alpha)
        .replace(".", "p")
    )

    tag = (
        f"{label}_"
        f"{correction}_"
        f"a{alpha_tag}_"
        f"{iea_tag}_"
        f"{h}"
    )

    raw_path = (
        raw_dir
        / f"gprofiler_{tag}.json"
    )

    request_path = (
        raw_dir
        / f"gprofiler_{tag}_request.json"
    )

    payload = {

        "organism":
            GPROFILER_ORGANISM,

        "query":
            genes,

        "sources":
            GPROFILER_SOURCES,

        "user_threshold":
            alpha,

        "significance_threshold_method":
            correction,

        "ordered":
            False,

        "all_results":
            False,

        "measure_underrepresentation":
            False,

        "no_iea":
            exclude_iea,

        # Preserve intersections/evidence.
        "no_evidences":
            False,

        "domain_scope":
            "annotated",
    }

    if background is not None:

        payload["background"] = (
            background
        )

        payload["domain_scope"] = (
            "custom_annotated"
        )

    write_json(
        request_path,
        payload,
    )

    if (
        raw_path.exists()
        and not refresh
    ):

        print(
            f"Using cached "
            f"g:Profiler result: "
            f"{raw_path.name}"
        )

        raw = read_json(
            raw_path
        )

    else:

        print(
            f"Running g:Profiler: "
            f"{label}"
        )

        response = request_with_retry(
            session,
            "POST",
            (
                f"{GPROFILER_BASE}"
                "/gost/profile/"
            ),
            json=payload,
        )

        raw = response.json()

        write_json(
            raw_path,
            raw,
        )

    results = raw.get(
        "result",
        [],
    )

    df = pd.DataFrame(
        results
    )

    if df.empty:

        print(
            f"No significant terms "
            f"for {label}."
        )

        df.to_csv(
            processed_dir
            / f"enrichment_{label}.csv",
            index=False,
        )

        return df

    df.rename(
        columns={
            "p_value":
                "adjusted_p_value"
        },
        inplace=True,
    )

    df.insert(
        0,
        "query_label",
        label,
    )

    df.insert(
        1,
        "input_gene_count",
        len(genes),
    )

    df.insert(
        2,
        "background_mode",
        (
            "master_candidate_background"
            if background is not None
            else "annotated_mouse_genome"
        ),
    )

    # Convert nested JSON fields safely
    # for CSV storage.
    for col in df.columns:

        if df[col].map(
            lambda x:
                isinstance(
                    x,
                    (list, dict),
                )
        ).any():

            df[col] = df[col].map(
                lambda x:
                    json.dumps(x)
                    if isinstance(
                        x,
                        (list, dict),
                    )
                    else x
            )

    df.sort_values(
        [
            "source",
            "adjusted_p_value",
        ],
        inplace=True,
    )

    df.to_csv(
        processed_dir
        / f"enrichment_{label}.csv",
        index=False,
    )

    return df


def plot_enrichment(
    df,
    label,
    figures_dir,
    top_n=15,
):

    if (
        df.empty
        or "adjusted_p_value"
        not in df.columns
    ):
        return

    for source in (
        GPROFILER_SOURCES
    ):

        sub = df[
            df["source"] == source
        ].copy()

        if sub.empty:
            continue

        sub = sub.nsmallest(
            top_n,
            "adjusted_p_value",
        )

        sub["score"] = (
            sub[
                "adjusted_p_value"
            ].map(
                lambda p:
                    -math.log10(
                        max(
                            float(p),
                            sys.float_info.min,
                        )
                    )
            )
        )

        labels = (
            sub["name"]
            .astype(str)
            .map(
                lambda x:
                    x
                    if len(x) <= 70
                    else x[:67] + "..."
            )
        )

        height = max(
            4,
            len(sub) * 0.42 + 1.5,
        )

        plt.figure(
            figsize=(10, height)
        )

        y = range(
            len(sub)
        )

        plt.barh(
            y,
            sub["score"],
        )

        plt.yticks(
            y,
            labels,
        )

        plt.gca().invert_yaxis()

        plt.xlabel(
            "-log10(adjusted p-value)"
        )

        plt.title(
            f"{label}: "
            f"{source}"
        )

        plt.tight_layout()

        source_name = (
            source.replace(
                ":",
                "_",
            )
        )

        plt.savefig(
            figures_dir
            / (
                f"enrichment_"
                f"{label}_"
                f"{source_name}.png"
            ),
            dpi=300,
            bbox_inches="tight",
        )

        plt.close()


