def load_gene_sets(workbook_path):

    xls = pd.ExcelFile(
        workbook_path
    )

    required = [
        MASTER_SHEET,
        COMMON_SHEET,
    ]

    missing = [
        s
        for s in required
        if s not in xls.sheet_names
    ]

    if missing:

        raise ValueError(
            "Missing sheet(s): "
            + ", ".join(missing)
        )

    master = pd.read_excel(
        workbook_path,
        sheet_name=MASTER_SHEET,
    )

    common = pd.read_excel(
        workbook_path,
        sheet_name=COMMON_SHEET,
    )

    for df in [master, common]:

        if "Gene" not in df.columns:

            raise ValueError(
                "Expected a 'Gene' column."
            )

        df["Gene"] = df[
            "Gene"
        ].map(clean_gene)

        df.dropna(
            subset=["Gene"],
            inplace=True,
        )

        df.drop_duplicates(
            "Gene",
            keep="first",
            inplace=True,
        )

        df.reset_index(
            drop=True,
            inplace=True,
        )

    # Sanity check.
    outside = (
        set(common["Gene"])
        - set(master["Gene"])
    )

    if outside:

        raise ValueError(
            "Common genes absent from master: "
            + ", ".join(sorted(outside))
        )

    return master, common


