def clean_gene(x):
    if pd.isna(x):
        return None

    x = str(x).strip()

    if not x:
        return None

    return x.upper()


def unique_ordered(values):
    seen = set()
    output = []

    for value in values:
        if value not in seen:
            seen.add(value)
            output.append(value)

    return output


def write_json(path, obj):
    path.write_text(
        json.dumps(
            obj,
            indent=2,
            ensure_ascii=False,
            default=str,
        ),
        encoding="utf-8",
    )


def read_json(path):
    return json.loads(
        path.read_text(encoding="utf-8")
    )


def sha256_file(path):
    h = hashlib.sha256()

    with path.open("rb") as f:
        while True:
            chunk = f.read(1024 * 1024)

            if not chunk:
                break

            h.update(chunk)

    return h.hexdigest()


def gene_hash(genes):
    text = "|".join(genes)

    return hashlib.sha256(
        text.encode("utf-8")
    ).hexdigest()[:10]


def request_with_retry(
    session,
    method,
    url,
    **kwargs,
):

    last_error = None

    for attempt in range(
        1,
        HTTP_RETRIES + 1,
    ):

        try:

            response = session.request(
                method,
                url,
                timeout=HTTP_TIMEOUT,
                **kwargs,
            )

            response.raise_for_status()

            return response

        except requests.RequestException as exc:

            last_error = exc

            if attempt < HTTP_RETRIES:

                wait = 2 ** (attempt - 1)

                print(
                    f"HTTP error: {exc}"
                )

                print(
                    f"Retrying in {wait}s..."
                )

                time.sleep(wait)

    raise RuntimeError(
        f"HTTP request failed: {last_error}"
    )


