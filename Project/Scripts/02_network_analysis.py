def map_string_ids(
    session,
    genes,
    raw_dir,
    processed_dir,
    *,
    refresh=False,
):

    h = gene_hash(
        genes
    )

    raw_path = (
        raw_dir
        / f"string_mapping_{h}.tsv"
    )

    request_path = (
        raw_dir
        / f"string_mapping_{h}_request.json"
    )

    params = {

        "identifiers":
            "\r".join(genes),

        "species":
            MOUSE_TAXON,

        "echo_query":
            1,

        "caller_identity":
            CALLER_IDENTITY,
    }

    write_json(
        request_path,
        params,
    )

    if (
        raw_path.exists()
        and not refresh
    ):

        print(
            "Using cached "
            "STRING mapping."
        )

        text = (
            raw_path.read_text(
                encoding="utf-8"
            )
        )

    else:

        print(
            "Mapping genes to "
            "STRING IDs..."
        )

        response = request_with_retry(
            session,
            "POST",
            (
                f"{STRING_BASE}"
                "/tsv/get_string_ids"
            ),
            data=params,
        )

        text = response.text

        raw_path.write_text(
            text,
            encoding="utf-8",
        )

        time.sleep(1)

    mapping = pd.read_csv(
        io.StringIO(text),
        sep="\t",
    )

    mapping[
        "queryItem"
    ] = mapping[
        "queryItem"
    ].map(clean_gene)

    # STRING normally returns one
    # best hit per submitted identifier.
    mapping = (
        mapping
        .sort_values(
            "queryIndex"
        )
        .drop_duplicates(
            "queryItem",
            keep="first",
        )
    )

    mapped = set(
        mapping["queryItem"]
    )

    unmapped = pd.DataFrame(
        {
            "Gene": [
                gene
                for gene in genes
                if gene not in mapped
            ]
        }
    )

    # Detect aliases mapping to the same
    # STRING protein.
    collisions = (
        mapping
        .groupby(
            "stringId"
        )["queryItem"]
        .agg(
            lambda x:
                ";".join(
                    sorted(set(x))
                )
        )
        .reset_index(
            name="input_genes"
        )
    )

    collisions[
        "n_input_genes"
    ] = (
        collisions[
            "input_genes"
        ].str.count(";")
        + 1
    )

    collisions = (
        collisions[
            collisions[
                "n_input_genes"
            ] > 1
        ]
    )

    mapping.to_csv(
        processed_dir
        / "string_mapping.csv",
        index=False,
    )

    unmapped.to_csv(
        processed_dir
        / "string_unmapped_genes.csv",
        index=False,
    )

    collisions.to_csv(
        processed_dir
        / "string_mapping_collisions.csv",
        index=False,
    )

    return (
        mapping,
        unmapped,
        collisions,
    )


