def update_workbook(
    input_path,
    output_path,
    nodes,
    required_score,
    network_type,
):

    shutil.copy2(
        input_path,
        output_path,
    )

    wb = load_workbook(
        output_path
    )

    ws = wb[
        MASTER_SHEET
    ]

    headers = {
        str(cell.value)
        .strip()
        .lower():
            cell.column

        for cell in ws[1]

        if cell.value
        is not None
    }

    required = [
        "gene",
        "degree",
        "betweenness",
        "pagerank",
        "community",
        "network notes",
    ]

    missing = [
        h
        for h in required
        if h not in headers
    ]

    if missing:

        raise ValueError(
            "Missing workbook "
            "column(s): "
            + ", ".join(missing)
        )

    lookup = (
        nodes
        .drop_duplicates("Gene")
        .set_index("Gene")
    )

    gene_col = headers[
        "gene"
    ]

    for row in range(
        2,
        ws.max_row + 1,
    ):

        gene = clean_gene(
            ws.cell(
                row,
                gene_col,
            ).value
        )

        if (
            not gene
            or gene
            not in lookup.index
        ):
            continue

        rec = lookup.loc[
            gene
        ]

        if pd.notna(
            rec.get("degree")
        ):

            ws.cell(
                row,
                headers["degree"],
            ).value = int(
                rec["degree"]
            )

            ws.cell(
                row,
                headers["betweenness"],
            ).value = float(
                rec[
                    "betweenness_weighted"
                ]
            )

            ws.cell(
                row,
                headers["pagerank"],
            ).value = float(
                rec["pagerank"]
            )

            ws.cell(
                row,
                headers["community"],
            ).value = int(
                rec["community"]
            )

        notes = []

        if (
            rec.get(
                "mapping_status"
            )
            == "unmapped"
        ):

            notes.append(
                "STRING v12.0: unmapped"
            )

        elif bool(
            rec.get(
                "isolate",
                False,
            )
        ):

            notes.append(
                "STRING v12.0: "
                f"isolate at score >= "
                f"{required_score}"
            )

        if notes:

            ws.cell(
                row,
                headers[
                    "network notes"
                ],
            ).value = "; ".join(
                notes
            )

    method = (
        f"STRING v12.0; "
        f"Mus musculus; "
        f"{network_type}; "
        f"required_score >= "
        f"{required_score}; "
        f"add_nodes=0. "
        "Weighted betweenness uses "
        "distance = 1 / STRING score."
    )

    ws.cell(
        1,
        headers["degree"],
    ).comment = Comment(
        method,
        "R-Noel pipeline",
    )

    ws.cell(
        1,
        headers["betweenness"],
    ).comment = Comment(
        method,
        "R-Noel pipeline",
    )

    ws.cell(
        1,
        headers["pagerank"],
    ).comment = Comment(
        method,
        "R-Noel pipeline",
    )

    ws.cell(
        1,
        headers["community"],
    ).comment = Comment(
        method,
        "R-Noel pipeline",
    )

    wb.save(
        output_path
    )


