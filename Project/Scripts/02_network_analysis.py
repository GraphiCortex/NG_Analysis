def build_graph(
    mapping,
    edges,
):

    G = nx.Graph()

    # Add mapped genes first so isolates are
    # retained even when STRING reports no edge.
    for _, row in mapping.iterrows():

        G.add_node(
            row["stringId"],
            gene=row["queryItem"],
            preferredName=row[
                "preferredName"
            ],
        )

    if edges.empty:

        return G

    for _, row in edges.iterrows():

        a = row[
            "stringId_A"
        ]

        b = row[
            "stringId_B"
        ]

        if a == b:
            continue

        score = float(
            row["score"]
        )

        # Confidence is a similarity/
        # strength measure.
        # Shortest-path algorithms need a
        # distance, so invert the score.
        distance = (
            1.0
            / max(score, 1e-12)
        )

        G.add_edge(
            a,
            b,
            score=score,
            distance=distance,
        )

    return G


def pagerank_power(
    G,
    alpha=0.85,
    max_iter=500,
    tol=1e-12,
):

    """
    Simple weighted PageRank power iteration.

    Avoids requiring scipy.
    """

    n = G.number_of_nodes()

    if n == 0:
        return {}

    nodes = list(G.nodes())

    rank = {
        node: 1.0 / n
        for node in nodes
    }

    strength = {
        node:
            sum(
                G[node][nbr].get(
                    "score",
                    1.0,
                )
                for nbr
                in G.neighbors(node)
            )
        for node in nodes
    }

    for _ in range(max_iter):

        new_rank = {
            node:
                (1 - alpha) / n
            for node in nodes
        }

        dangling = sum(
            rank[node]
            for node in nodes
            if strength[node] == 0
        )

        dangling_share = (
            alpha
            * dangling
            / n
        )

        for node in nodes:

            new_rank[node] += (
                dangling_share
            )

        for node in nodes:

            if strength[node] == 0:
                continue

            for nbr in G.neighbors(
                node
            ):

                weight = (
                    G[node][nbr]
                    .get(
                        "score",
                        1.0,
                    )
                )

                new_rank[nbr] += (
                    alpha
                    * rank[node]
                    * weight
                    / strength[node]
                )

        diff = sum(
            abs(
                new_rank[node]
                - rank[node]
            )
            for node in nodes
        )

        rank = new_rank

        if diff < tol:
            break

    total = sum(
        rank.values()
    )

    return {
        node:
            value / total
        for node, value
        in rank.items()
    }


def get_communities(G):

    if G.number_of_nodes() == 0:
        return {}

    if G.number_of_edges() == 0:

        return {
            node: i + 1
            for i, node
            in enumerate(G)
        }

    communities = list(
        nx.community
        .greedy_modularity_communities(
            G,
            weight="score",
        )
    )

    communities.sort(
        key=len,
        reverse=True,
    )

    result = {}

    for cid, community in enumerate(
        communities,
        start=1,
    ):

        for node in community:
            result[node] = cid

    return result


def graph_diagnostics(G):

    n = G.number_of_nodes()

    components = (
        sorted(
            nx.connected_components(G),
            key=len,
            reverse=True,
        )
        if n
        else []
    )

    return {

        "number_of_nodes":
            n,

        "number_of_edges":
            G.number_of_edges(),

        "number_of_isolates":
            len(
                list(
                    nx.isolates(G)
                )
            ),

        "number_of_connected_components":
            len(components),

        "largest_component_size":
            (
                len(components[0])
                if components
                else 0
            ),

        "largest_component_fraction":
            (
                len(components[0]) / n
                if components and n
                else 0
            ),

        "density":
            (
                nx.density(G)
                if n > 1
                else 0
            ),

        "average_degree":
            (
                sum(
                    dict(
                        G.degree()
                    ).values()
                )
                / n
                if n
                else 0
            ),

        "component_sizes":
            [
                len(c)
                for c in components
            ],
    }


def compute_metrics(G):

    if G.number_of_nodes() == 0:

        return pd.DataFrame()

    degree = dict(
        G.degree()
    )

    weighted_degree = dict(
        G.degree(
            weight="score"
        )
    )

    degree_centrality = (
        nx.degree_centrality(G)
    )

    betweenness = (
        nx.betweenness_centrality(
            G,
            normalized=True,
            weight="distance",
        )
    )

    betweenness_unweighted = (
        nx.betweenness_centrality(
            G,
            normalized=True,
            weight=None,
        )
    )

    closeness = (
        nx.closeness_centrality(
            G,
            distance="distance",
        )
    )

    pagerank = (
        pagerank_power(G)
    )

    community = (
        get_communities(G)
    )

    components = sorted(
        nx.connected_components(G),
        key=len,
        reverse=True,
    )

    component_id = {}
    component_size = {}

    for cid, comp in enumerate(
        components,
        start=1,
    ):

        for node in comp:

            component_id[node] = (
                cid
            )

            component_size[node] = (
                len(comp)
            )

    rows = []

    for node in G.nodes():

        rows.append({

            "stringId":
                node,

            "graph_gene":
                G.nodes[node]
                .get(
                    "gene",
                    "",
                ),

            "preferredName":
                G.nodes[node]
                .get(
                    "preferredName",
                    "",
                ),

            "degree":
                degree[node],

            "weighted_degree":
                weighted_degree[node],

            "degree_centrality":
                degree_centrality[node],

            "betweenness_weighted":
                betweenness[node],

            "betweenness_unweighted":
                betweenness_unweighted[
                    node
                ],

            "closeness_weighted":
                closeness[node],

            "pagerank":
                pagerank[node],

            "community":
                community[node],

            "component_id":
                component_id[node],

            "component_size":
                component_size[node],

            "isolate":
                degree[node] == 0,
        })

    return pd.DataFrame(
        rows
    )


